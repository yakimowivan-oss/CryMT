"""Generates the ID3D10Device1 forwarders of the D3D layer from llvm-mingw's d3d10_1.h.
gen_d3d10_wrap.py <d3d10_1.h> <out .inc>
Each forwarder counts its call and calls the same slot of the real device through the real device's current vtable
(the D3D10-on-11 runtime keeps a per-device vtable it rewrites). Slots 0-2 (QueryInterface, AddRef, Release) are
written by hand in D3DLayer.cpp."""
import re
import sys

text = open(sys.argv[1], encoding="latin1").read()
body = re.search(r"typedef struct ID3D10Device1Vtbl\s*\{(.*?)\}\s*ID3D10Device1Vtbl;", text, re.S).group(1)
methods = re.findall(r"(\w[\w\s\*]*?)\s*\(\s*STDMETHODCALLTYPE \*(\w+)\)\s*\((.*?)\);", body, re.S)


def split_args(args):
    out, depth, cur = [], 0, ""
    for ch in args:
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
            continue
        depth += ch == "("
        depth -= ch == ")"
        cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


lines = ["// Generated by tools\\prof\\gen_d3d10_wrap.py from d3d10_1.h; do not edit.",
         f"constexpr int kWrapSlots = {len(methods)};"]
names = []
for slot, (ret, name, args) in enumerate(methods):
    names.append(name)
    if slot < 3:
        continue
    ret = " ".join(ret.split())
    params = split_args(" ".join(args.split()))[1:]  # drop "ID3D10Device1 *This"
    decl = ", ".join(params)
    pnames, types = [], []
    for p in params:
        m = re.search(r"(\w+)\s*(\[\d*\])?\s*$", p)
        pnames.append(m.group(1))
        base = p[: m.start(1)].strip()
        types.append(base + "*" if m.group(2) else base)  # an array parameter is a pointer
    fn_type = f"{ret}(STDMETHODCALLTYPE*)(ID3D10Device1*{''.join(', ' + t for t in types)})"
    call_args = "".join(", " + n for n in pnames)
    lines.append(f"{ret} STDMETHODCALLTYPE W_{name}(ID3D10Device1* This{', ' + decl if decl else ''})")
    lines.append("{")
    lines.append(f"    Count({slot});")
    lines.append(f"    return reinterpret_cast<{fn_type}>(RealSlot(This, {slot}))(Real(This){call_args});")
    lines.append("}")
lines.append("const void* const kWrapVtable[kWrapSlots] = {")
lines.append("    reinterpret_cast<const void*>(&W_QueryInterface), reinterpret_cast<const void*>(&W_AddRef), reinterpret_cast<const void*>(&W_Release),")
for name in names[3:]:
    lines.append(f"    reinterpret_cast<const void*>(&W_{name}),")
lines.append("};")
lines.append("const char* const kWrapNames[kWrapSlots] = {" + ", ".join(f'"{n}"' for n in names) + "};")
open(sys.argv[2], "w").write("\n".join(lines) + "\n")
print("methods:", len(methods))
