# Generates the forwarding part of the Bin64\dbghelp.dll proxy (src\crymt\proxy): every export of the system
# dbghelp.dll becomes a stub that jumps through a table the proxy fills from the real DLL at load.
# Usage: python mkproxy.py <llvm-objdump> <out dir>
import os
import re
import subprocess
import sys

objdump, out = sys.argv[1], sys.argv[2]
system = os.path.join(os.environ['SystemRoot'], 'System32', 'dbghelp.dll')
text = subprocess.run([objdump, '-p', system], capture_output=True, text=True).stdout
names = []
in_exports = False
for line in text.splitlines():
    if line.startswith('Export Table'):
        in_exports = True
        continue
    if in_exports:
        # Forwarded exports (MiniDumpWriteDump -> dbgcore) have no RVA; GetProcAddress resolves them all the same.
        m = re.match(r'\s+\d+\s+(?:0x[0-9a-f]+\s+)?(\S+)(?:\s+\(forwarded to \S+\))?\s*$', line)
        if m:
            names.append(m.group(1))
        elif line.strip() == '' and names:
            break
names = sorted(set(names))
if not names:
    sys.exit('no exports found')

with open(os.path.join(out, 'DbgHelpExports.h'), 'w', newline='\n') as f:
    f.write('#pragma once\n// Generated by tools\\prof\\mkproxy.py from the system dbghelp.dll; %d exports.\n' % len(names))
    f.write('constexpr int kDbgHelpExports = %d;\n' % len(names))
    f.write('constexpr const char* kDbgHelpNames[kDbgHelpExports] = {\n')
    for n in names:
        f.write('    "%s",\n' % n)
    f.write('};\n')
with open(os.path.join(out, 'DbgHelpStubs.S'), 'w', newline='\n') as f:
    f.write('// Generated by tools\\prof\\mkproxy.py: one jump per dbghelp export through g_dbghelp (filled in DllMain).\n')
    f.write('.intel_syntax noprefix\n.text\n')
    for i, n in enumerate(names):
        f.write('.globl proxy_%d\nproxy_%d:\n    jmp qword ptr [rip + g_dbghelp + %d]\n' % (i, i, i * 8))
with open(os.path.join(out, 'DbgHelp.def'), 'w', newline='\n') as f:
    f.write('LIBRARY dbghelp\nEXPORTS\n')
    for i, n in enumerate(names):
        f.write('    %s=proxy_%d\n' % (n, i))
print(len(names), 'exports')
